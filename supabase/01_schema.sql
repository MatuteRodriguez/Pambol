-- Tendencia de la comunidad en la quiniela (solo totales, nunca picks individuales)
create or replace function public.fixture_trends(p_gw integer)
returns table (fixture_id integer, total bigint, home_pct integer, draw_pct integer, away_pct integer)
language sql stable security definer set search_path = public as $$
  select q.fixture_id, count(*),
    round(100.0 * count(*) filter (where q.home_score > q.away_score) / count(*))::int,
    round(100.0 * count(*) filter (where q.home_score = q.away_score) / count(*))::int,
    round(100.0 * count(*) filter (where q.home_score < q.away_score) / count(*))::int
  from public.quiniela_picks q join public.fixtures f on f.id = q.fixture_id
  where f.gameweek_id = p_gw group by q.fixture_id;
$$;

-- Desglose en vivo de mi equipo (si no guardé, se usa el de la jornada anterior)
create or replace function public.my_team_breakdown(p_gw integer)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare t public.fantasy_teams;
begin
  if auth.uid() is null then return null; end if;
  select * into t from public.fantasy_teams where user_id = auth.uid() and gameweek_id = p_gw;
  if t.id is null then
    t := public.pambol_baseline_team(auth.uid(), p_gw);
    if t.id is null then return null; end if;
    return public.pambol_score_squad(p_gw, t.starters, t.bench, t.captain_id, t.modifiers, 'NONE', t.coach_id, 0)
           || jsonb_build_object('carried_over', true);
  end if;
  return public.pambol_score_team(t.id);
end $$;

-- Desglose de cualquier equipo, solo después del primer silbatazo
create or replace function public.team_breakdown(p_team_id integer)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare t public.fantasy_teams;
begin
  select * into t from public.fantasy_teams where id = p_team_id;
  if t.id is null then return null; end if;
  if t.user_id <> auth.uid() and coalesce(public.gw_deadline(t.gameweek_id) > now(), true) and not public.is_admin() then
    raise exception 'Este equipo se revela al iniciar la jornada';
  end if;
  return coalesce(t.breakdown, public.pambol_score_team(t.id));
end $$;

-- Premios de la jornada: Once Ideal, DT de la Fecha, Hachero de Oro, Tronco
create or replace function public.gameweek_awards(p_gw integer)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_ideal jsonb;
  v_top jsonb;
  v_axe jsonb;
  v_wood jsonb;
  v_gw public.gameweeks;
begin
  select * into v_gw from public.gameweeks where id = p_gw;
  with pts as (
    select s.player_id, p.name, p.pos, p.club_short, p.squad_number, sum(s.base_points) pts, sum(s.fouls) fouls, sum(s.minutes) mins
    from public.player_stats s join public.fixtures f on f.id = s.fixture_id join public.players p on p.id = s.player_id
    where f.gameweek_id = p_gw group by s.player_id, p.name, p.pos, p.club_short, p.squad_number
  ), ranked as (
    select *, row_number() over (partition by pos order by pts desc, mins desc, name) rn from pts where mins > 0
  )
  select jsonb_agg(jsonb_build_object('id', player_id, 'name', name, 'pos', pos, 'club', club_short, 'number', squad_number, 'points', pts) order by pos, pts desc)
    into v_ideal
  from ranked where (pos = 'GK' and rn = 1) or (pos = 'DEF' and rn <= 4) or (pos = 'MID' and rn <= 3) or (pos = 'FWD' and rn <= 3);

  select jsonb_build_object('username', p.username, 'club', p.favorite_club, 'points', t.points) into v_top
  from public.fantasy_teams t join public.profiles p on p.id = t.user_id
  where t.gameweek_id = p_gw and t.scored_at is not null order by t.points desc, t.updated_at limit 1;

  select jsonb_build_object('name', p.name, 'club', s.club_short, 'fouls', sum(s.fouls)) into v_axe
  from public.player_stats s join public.fixtures f on f.id = s.fixture_id join public.players p on p.id = s.player_id
  where f.gameweek_id = p_gw group by p.name, s.club_short having sum(s.fouls) > 0 order by sum(s.fouls) desc, p.name limit 1;

  select jsonb_build_object('name', p.name, 'club', s.club_short, 'points', sum(s.base_points)) into v_wood
  from public.player_stats s join public.fixtures f on f.id = s.fixture_id join public.players p on p.id = s.player_id
  where f.gameweek_id = p_gw and s.minutes > 0 group by p.name, s.club_short order by sum(s.base_points), p.name limit 1;

  return jsonb_build_object('gameweek', p_gw, 'number', v_gw.number, 'name', v_gw.name, 'scored', v_gw.status = 'scored',
    'ideal', coalesce(v_ideal, '[]'::jsonb), 'top_manager', v_top, 'axe', v_axe, 'wood', v_wood);
end $$;


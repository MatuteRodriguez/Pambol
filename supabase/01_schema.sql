-- 8. MOTOR DE PUNTUACIÓN (REGLAMENTO OFICIAL PAMBOL)
--    100 % determinista: solo usa el acta cargada por el administrador.
-- =====================================================================
-- Puntos de un jugador en un partido. p_mod = modificador equipado ('NONE' si ninguno)
create or replace function public.pambol_stat_points(
  s public.player_stats, p_pos text, p_mod text default 'NONE'
) returns jsonb language plpgsql stable as $$
declare
  f public.fixtures;
  v_home boolean;
  v_conceded int;
  v_opponent text;
  v_ex text[];
  pts numeric := 0;
  lines jsonb := '[]'::jsonb;
  v numeric;
  goal_val int;
  open_goals int;
  neg numeric := 0;
begin
  select * into f from public.fixtures where id = s.fixture_id;
  if s.minutes <= 0 then
    return jsonb_build_object('points', 0, 'lines', jsonb_build_array(jsonb_build_array('No jugó', 0)));
  end if;
  v_home := (f.home_club = s.club_short);
  v_opponent := case when v_home then f.away_club else f.home_club end;
  v_conceded := case when v_home then f.away_score else f.home_score end;
  select ex_clubs into v_ex from public.players where id = s.player_id;

  -- Minutos
  if p_mod = 'REVULSIVO' and not s.started then
    v := 2; lines := lines || jsonb_build_array(jsonb_build_array('⚡ Revulsivo: minutos como 90''', v));
  elsif s.minutes >= 60 then
    v := 2; lines := lines || jsonb_build_array(jsonb_build_array('⏱️ ' || s.minutes || ' minutos', v));
  else
    v := 1; lines := lines || jsonb_build_array(jsonb_build_array('⏱️ ' || s.minutes || ' minutos', v));
  end if;
  pts := pts + v;

  -- Goles
  if s.goals > 0 then
    goal_val := case p_pos when 'FWD' then 4 when 'MID' then 5 when 'DEF' then 7 else 10 end;
    open_goals := s.goals - s.penalty_goals;
    v := open_goals * goal_val + s.penalty_goals * 3;
    if p_mod = 'LEYEX' and v_opponent = any(coalesce(v_ex, '{}')) then
      v := v * 2;
      lines := lines || jsonb_build_array(jsonb_build_array('🏹 Ley del Ex: ' || s.goals || ' gol(es) x2', v));
    else
      if open_goals > 0 then lines := lines || jsonb_build_array(jsonb_build_array('⚽ ' || open_goals || ' gol(es)', open_goals * goal_val)); end if;
      if s.penalty_goals > 0 then lines := lines || jsonb_build_array(jsonb_build_array('⚽ ' || s.penalty_goals || ' gol(es) de penal', s.penalty_goals * 3)); end if;
    end if;
    pts := pts + v;
    if not v_home then
      pts := pts + s.goals;
      lines := lines || jsonb_build_array(jsonb_build_array('✈️ Gol de visitante', s.goals));
    end if;
  end if;
  if s.golden_goals > 0 then
    v := s.golden_goals * 4; pts := pts + v;
    lines := lines || jsonb_build_array(jsonb_build_array('🥇 Gol agónico (80''+)', v));
  end if;

  -- Asistencias
  if s.assists > 0 then
    v := s.assists * 3; pts := pts + v;
    lines := lines || jsonb_build_array(jsonb_build_array('🎯 ' || s.assists || ' asistencia(s)', v));
  end if;
  if s.pre_assists > 0 then
    v := s.pre_assists * 1.5; pts := pts + v;
    lines := lines || jsonb_build_array(jsonb_build_array('👟 ' || s.pre_assists || ' pre-asistencia(s)', v));
  end if;
  if s.set_piece_goals + s.set_piece_assists > 0 then
    v := (s.set_piece_goals + s.set_piece_assists) * 3; pts := pts + v;
    lines := lines || jsonb_build_array(jsonb_build_array('🎯 Balón parado', v));
  end if;

  -- Valla invicta (60'+)
  if s.minutes >= 60 and v_conceded = 0 and f.status in ('live','finished') and p_pos in ('GK','DEF') then
    v := case when p_pos = 'GK' then 4 else 3 end; pts := pts + v;
    lines := lines || jsonb_build_array(jsonb_build_array('🧤 Valla invicta', v));
  end if;

  -- Portero
  if s.saves >= 3 then
    v := floor(s.saves / 3.0); pts := pts + v;
    lines := lines || jsonb_build_array(jsonb_build_array('🧤 ' || s.saves || ' atajadas', v));
  end if;
  if s.penalties_saved > 0 then
    v := s.penalties_saved * 5; pts := pts + v;
    lines := lines || jsonb_build_array(jsonb_build_array('🧤 Penal atajado', v));
  end if;
  if s.penalties_missed > 0 then
    v := s.penalties_missed * -3; pts := pts + v;
    lines := lines || jsonb_build_array(jsonb_build_array('❌ Penal errado', v));
  end if;

  -- Disciplina (El Paro la anula)
  neg := s.yellow_cards * -1 + s.red_cards * -3 + s.penalties_committed * -2;
  if neg < 0 then
    if p_mod = 'PARO' then
      lines := lines || jsonb_build_array(jsonb_build_array('🛡️ El Paro anuló sanciones', 0));
    else
      if s.yellow_cards > 0 then lines := lines || jsonb_build_array(jsonb_build_array('🟨 Amarilla', s.yellow_cards * -1)); end if;
      if s.red_cards > 0 then lines := lines || jsonb_build_array(jsonb_build_array('🟥 Roja', -3)); end if;
      if s.penalties_committed > 0 then lines := lines || jsonb_build_array(jsonb_build_array('⚠️ Penal cometido', s.penalties_committed * -2)); end if;
      pts := pts + neg;
    end if;
  end if;

  -- Modificadores de rendimiento
  if p_mod = 'HACHERO' then
    if s.fouls >= 4 then pts := pts + 5; lines := lines || jsonb_build_array(jsonb_build_array('🪓 El Hachero (' || s.fouls || ' faltas)', 5));
    else lines := lines || jsonb_build_array(jsonb_build_array('🪓 El Hachero no se cumplió (' || s.fouls || ' faltas)', 0)); end if;
  elsif p_mod = 'CHULADA' then
    if s.dribbles >= 3 then pts := pts + 3; lines := lines || jsonb_build_array(jsonb_build_array('✨ La Chulada (' || s.dribbles || ' regates)', 3));
    else lines := lines || jsonb_build_array(jsonb_build_array('✨ La Chulada no se cumplió (' || s.dribbles || ' regates)', 0)); end if;
  end if;

  return jsonb_build_object('points', pts, 'lines', lines);
end $$;

-- Recalcula los puntos base del acta (sin modificadores) al guardar
create or replace function public.player_stats_compute()
returns trigger language plpgsql as $$
declare
  v_pos text;
  r jsonb;
begin
  select pos into v_pos from public.players where id = new.player_id;
  if new.club_short is null then
    select club_short into new.club_short from public.players where id = new.player_id;
  end if;
  r := public.pambol_stat_points(new, v_pos, 'NONE');
  new.base_points := (r->>'points')::numeric;
  new.breakdown := r->'lines';
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists player_stats_compute on public.player_stats;
create trigger player_stats_compute before insert or update on public.player_stats
  for each row execute function public.player_stats_compute();

-- Si cambia el marcador, se recalculan las vallas invictas de ese partido
create or replace function public.fixtures_after_change()
returns trigger language plpgsql as $$
begin
  if (new.home_score is distinct from old.home_score) or (new.away_score is distinct from old.away_score)
     or (new.status is distinct from old.status) then
    update public.player_stats set updated_at = now() where fixture_id = new.id;
  end if;
  return null;
end $$;

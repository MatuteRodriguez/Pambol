-- Quiniela: se cierra al silbatazo de cada partido
create or replace function public.quiniela_validate()
returns trigger language plpgsql set search_path = public as $$
declare v_fix public.fixtures;
begin
  if not public.pambol_is_api_role() then
    return case when tg_op = 'DELETE' then old else new end;
  end if;
  select * into v_fix from public.fixtures where id = case when tg_op = 'DELETE' then old.fixture_id else new.fixture_id end;
  if v_fix.id is null then raise exception 'Partido inexistente'; end if;
  if v_fix.kickoff_at <= now() or v_fix.status <> 'scheduled' then
    raise exception 'El partido % vs % ya comenzó: pronóstico cerrado', v_fix.home_club, v_fix.away_club;
  end if;
  if tg_op = 'DELETE' then
    if old.user_id <> auth.uid() then raise exception 'No autorizado'; end if;
    return old;
  end if;
  if new.user_id is distinct from auth.uid() then raise exception 'Solo puedes guardar tus pronósticos'; end if;
  if tg_op = 'UPDATE' and (new.user_id <> old.user_id or new.fixture_id <> old.fixture_id) then raise exception 'No autorizado'; end if;
  new.points := case when tg_op = 'UPDATE' then old.points else 0 end;
  new.updated_at := now();
  return new;
end $$;

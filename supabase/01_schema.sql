-- Código de liga: 6 caracteres sin letras confusas (~887 millones de combinaciones)
create or replace function public.pambol_new_code()
returns text language plpgsql volatile as $$
declare
  alphabet text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  b bytea := decode(substr(replace(gen_random_uuid()::text, '-', ''), 1, 12), 'hex');  -- 6 bytes aleatorios (núcleo de Postgres)
  out text := '';
  i int;
begin
  for i in 0..5 loop
    out := out || substr(alphabet, (get_byte(b, i) % 32) + 1, 1);
  end loop;
  return out;
end $$;

create or replace function public.create_league(p_name text, p_icon text default '⚽')
returns public.leagues language plpgsql security definer set search_path = public as $$
declare
  v public.leagues;
  v_code text;
begin
  if auth.uid() is null then raise exception 'Inicia sesión para crear una liga'; end if;
  if (select count(*) from public.leagues where creator_id = auth.uid()) >= 20 then
    raise exception 'Llegaste al máximo de 20 ligas creadas';
  end if;
  loop
    v_code := public.pambol_new_code();
    exit when not exists (select 1 from public.leagues where code = v_code);
  end loop;
  insert into public.leagues (name, code, icon, creator_id)
  values (trim(p_name), v_code, left(coalesce(nullif(p_icon, ''), '⚽'), 4), auth.uid())
  returning * into v;
  insert into public.league_members (league_id, user_id) values (v.id, auth.uid());
  return v;
end $$;

create or replace function public.join_league(p_code text)
returns public.leagues language plpgsql security definer set search_path = public as $$
declare v public.leagues;
begin
  if auth.uid() is null then raise exception 'Inicia sesión para unirte a una liga'; end if;
  select * into v from public.leagues where code = upper(regexp_replace(coalesce(p_code, ''), '[^A-Za-z0-9]', '', 'g'));
  if v.id is null then raise exception 'No existe ninguna liga con ese código'; end if;
  if (select count(*) from public.league_members where league_id = v.id) >= 500 then
    raise exception 'La liga está llena (500 miembros)';
  end if;
  insert into public.league_members (league_id, user_id) values (v.id, auth.uid()) on conflict do nothing;
  return v;
end $$;

-- Mis ligas con mi posición
create or replace function public.my_leagues()
returns table (id uuid, name text, code text, icon text, creator_id uuid, creator_name text, members bigint, my_rank bigint, my_pts numeric)
language sql stable security definer set search_path = public as $$
  with mine as (select league_id from public.league_members where user_id = auth.uid()),
  ranked as (
    select m.league_id, m.user_id, p.total_pts,
           rank() over (partition by m.league_id order by p.total_pts desc) rk,
           count(*) over (partition by m.league_id) n
    from public.league_members m join public.profiles p on p.id = m.user_id
    where m.league_id in (select league_id from mine)
  )
  select l.id, l.name, l.code, l.icon, l.creator_id, cp.username, r.n, r.rk, r.total_pts
  from ranked r join public.leagues l on l.id = r.league_id
  left join public.profiles cp on cp.id = l.creator_id
  where r.user_id = auth.uid()
  order by l.created_at;
$$;


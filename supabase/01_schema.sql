create or replace function public.pambol_require_admin()
returns void language plpgsql stable security definer set search_path = public as $$
begin
  -- session_user = postgres cuando se ejecuta desde el SQL Editor de Supabase
  if not (public.is_admin() or session_user in ('postgres', 'supabase_admin')
          or coalesce(current_setting('request.jwt.claims', true)::jsonb->>'role', '') = 'service_role') then
    raise exception 'Solo administradores';
  end if;
end $$;

create or replace function public.pambol_recompute_totals(p_tournament text)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform public.pambol_require_admin();
  update public.profiles p set
    total_fantasy_pts = coalesce(x.fpts, 0),
    total_quiniela_pts = coalesce(y.qpts, 0),
    total_champion_pts = coalesce(z.cpts, 0),
    total_pts = coalesce(x.fpts, 0) + coalesce(y.qpts, 0) + coalesce(z.cpts, 0),
    last_gw_pts = coalesce(w.last_pts, 0)
  from public.profiles p2
  left join (
    select t.user_id, sum(t.points) fpts from public.fantasy_teams t join public.gameweeks g on g.id = t.gameweek_id
    where g.tournament_id = p_tournament and t.scored_at is not null group by t.user_id) x on x.user_id = p2.id
  left join (
    select q.user_id, sum(q.points) qpts from public.quiniela_picks q join public.fixtures f on f.id = q.fixture_id
    join public.gameweeks g on g.id = f.gameweek_id where g.tournament_id = p_tournament group by q.user_id) y on y.user_id = p2.id
  left join (
    select c.user_id, sum(c.points) cpts from public.champion_picks c where c.tournament_id = p_tournament group by c.user_id) z on z.user_id = p2.id
  left join (
    select distinct on (t.user_id) t.user_id, t.points last_pts from public.fantasy_teams t join public.gameweeks g on g.id = t.gameweek_id
    where g.tournament_id = p_tournament and t.scored_at is not null order by t.user_id, g.number desc) w on w.user_id = p2.id
  where p.id = p2.id;

  update public.profiles p set national_rank = r.rk
  from (select id, rank() over (order by total_pts desc) rk from public.profiles) r where r.id = p.id;
end $$;

-- Puntúa (o vuelve a puntuar) una jornada completa. Se puede correr las veces que quieras.
create or replace function public.admin_score_gameweek(p_gw integer, p_close boolean default true)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_gw public.gameweeks;
  v_carried int := 0;
  v_teams int := 0;
  v_picks int := 0;
  v_pending int;
  u record;
  b public.fantasy_teams;
begin
  perform public.pambol_require_admin();
  select * into v_gw from public.gameweeks where id = p_gw;
  if v_gw.id is null then raise exception 'Jornada inexistente'; end if;

  -- 1) Arrastre: quien no guardó equipo juega con el de la jornada anterior
  for u in
    select p.id from public.profiles p
    where not exists (select 1 from public.fantasy_teams t where t.user_id = p.id and t.gameweek_id = p_gw)
  loop
    b := public.pambol_baseline_team(u.id, p_gw);
    if b.id is not null then
      insert into public.fantasy_teams (user_id, gameweek_id, formation, starters, bench, coach_id, captain_id, modifiers, chip)
      values (u.id, p_gw, b.formation, b.starters, b.bench, b.coach_id, b.captain_id, '{}'::jsonb, 'NONE');
      v_carried := v_carried + 1;
    end if;
  end loop;

  -- 2) Fantasy
  update public.fantasy_teams t set breakdown = public.pambol_score_team(t.id), scored_at = now()
  where t.gameweek_id = p_gw;
  update public.fantasy_teams t set points = (t.breakdown->>'total')::numeric where t.gameweek_id = p_gw;
  get diagnostics v_teams = row_count;

  -- 3) Quiniela 5-3-0 (solo partidos finalizados)
  update public.quiniela_picks q set points = case
      when q.home_score = f.home_score and q.away_score = f.away_score then 5
      when sign(q.home_score - q.away_score) = sign(f.home_score - f.away_score) then 3
      else 0 end
  from public.fixtures f
  where f.id = q.fixture_id and f.gameweek_id = p_gw and f.status = 'finished'
    and f.home_score is not null and f.away_score is not null;
  get diagnostics v_picks = row_count;

  -- 4) Cerrar jornada si todos los partidos terminaron
  select count(*) into v_pending from public.fixtures where gameweek_id = p_gw and status not in ('finished','postponed');
  if p_close and v_pending = 0 then
    update public.gameweeks set status = 'scored', scored_at = now() where id = p_gw;
  end if;

  perform public.pambol_recompute_totals(v_gw.tournament_id);
  return jsonb_build_object('carried_over', v_carried, 'teams_scored', v_teams, 'picks_scored', v_picks,
                            'pending_fixtures', v_pending, 'closed', p_close and v_pending = 0);
end $$;

-- Reabrir una jornada puntuada (para corregir un acta)
create or replace function public.admin_reopen_gameweek(p_gw integer)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform public.pambol_require_admin();
  update public.gameweeks set status = 'scheduled', scored_at = null where id = p_gw;
end $$;

-- Define el campeón del torneo y otorga +20 a quien lo pronosticó
create or replace function public.admin_set_champion(p_tournament text, p_club text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_n int;
begin
  perform public.pambol_require_admin();
  update public.tournaments set champion_club = p_club where id = p_tournament;
  update public.champion_picks set points = case when club_short = p_club then 20 else 0 end where tournament_id = p_tournament;
  get diagnostics v_n = row_count;
  perform public.pambol_recompute_totals(p_tournament);
  return jsonb_build_object('picks_scored', v_n);
end $$;

-- Marca un torneo como el actual
create or replace function public.admin_set_current_tournament(p_tournament text)
returns void language plpgsql security definer set search_path = public as $$
begin
  perform public.pambol_require_admin();
  update public.tournaments set is_current = false where is_current and id <> p_tournament;
  update public.tournaments set is_current = true where id = p_tournament;
end $$;

-- Nueva semana de cotizaciones: la tendencia (▲/▼) se mide contra este precio
create or replace function public.admin_snapshot_prices()
returns integer language plpgsql security definer set search_path = public as $$
declare v_n int;
begin
  perform public.pambol_require_admin();
  update public.players set prev_price = price where prev_price is distinct from price;
  get diagnostics v_n = row_count;
  return v_n;
end $$;


-- Equipo de referencia para una jornada: el de la jornada anterior más reciente
-- (si usó Fecha Libre, se regresa al equipo previo a esa jornada).
create or replace function public.pambol_baseline_team(p_user uuid, p_gw integer)
returns public.fantasy_teams language sql stable as $$
  select t.* from public.fantasy_teams t
  join public.gameweeks g on g.id = t.gameweek_id
  join public.gameweeks cur on cur.id = p_gw
  where t.user_id = p_user
    and g.tournament_id = cur.tournament_id
    and g.number < cur.number
    and t.chip <> 'FREE_HIT'
  order by g.number desc
  limit 1;
$$;

-- Ids de los 15 jugadores de una plantilla
create or replace function public.pambol_squad_ids(p_starters integer[], p_bench jsonb)
returns integer[] language sql immutable as $$
  select coalesce(p_starters, '{}') || array_remove(array[
    (p_bench->>'GK')::int, (p_bench->>'DEF')::int, (p_bench->>'MID')::int, (p_bench->>'FWD')::int], null);
$$;

-- Rol de un jugador dentro de una plantilla (para comparar cambios con veda)
create or replace function public.pambol_role(p_pid integer, p_starters integer[], p_bench jsonb, p_captain integer, p_mods jsonb)
returns text language sql immutable as $$
  select case
    when p_pid = any(coalesce(p_starters,'{}')) then 'XI'
    when p_pid in ((p_bench->>'GK')::int, (p_bench->>'DEF')::int, (p_bench->>'MID')::int, (p_bench->>'FWD')::int) then 'BANCA'
    else 'FUERA' end
    || case when p_pid = p_captain then ':C' else '' end
    || ':' || coalesce(p_mods->>(p_pid::text), 'NONE');
$$;


-- 9. VALIDACIÓN ANTI-TRAMPA DE EQUIPOS (se ejecuta en el servidor)
-- =====================================================================
create or replace function public.fantasy_teams_validate()
returns trigger language plpgsql set search_path = public as $$
declare
  v_gw public.gameweeks;
  v_base public.fantasy_teams;
  v_prev public.fantasy_teams;
  v_squad integer[];
  v_old_squad integer[];
  v_cnt jsonb;
  v_cost numeric;
  v_coach_price numeric;
  v_n int;
  v_locked text[];
  pid integer;
  v_club text;
  v_bpos text;
  v_key text;
  v_val text;
  b_starters integer[];
  b_bench jsonb;
  b_captain integer;
  b_mods jsonb;
  b_coach integer;
  b_chip text;
  v_def int; v_mid int; v_fwd int; v_gk int;
begin
  select * into v_gw from public.gameweeks where id = new.gameweek_id;
  if v_gw.id is null then raise exception 'Jornada inexistente'; end if;

  v_squad := public.pambol_squad_ids(new.starters, new.bench);

  -- Datos calculados (siempre)
  select count(*) filter (where pos = 'GK'), count(*) filter (where pos = 'DEF'),
         count(*) filter (where pos = 'MID'), count(*) filter (where pos = 'FWD')
    into v_gk, v_def, v_mid, v_fwd
    from public.players where id = any(new.starters);
  new.formation := v_def || '-' || v_mid || '-' || v_fwd;
  select coalesce(sum(price), 0) into v_cost from public.players where id = any(v_squad);
  select price into v_coach_price from public.coaches where id = new.coach_id;
  new.squad_cost := v_cost + coalesce(v_coach_price, 0);

  v_prev := public.pambol_baseline_team(new.user_id, new.gameweek_id);
  if v_prev.id is null then
    new.transfers := 0;
  else
    select count(*) into v_n from unnest(v_squad) x where not (x = any(public.pambol_squad_ids(v_prev.starters, v_prev.bench)));
    new.transfers := v_n;
  end if;
  new.transfer_penalty := case when new.chip = 'FREE_HIT' then 0 else greatest(0, new.transfers - 2) * 4 end;
  new.updated_at := now();

  -- Las reglas siguientes solo aplican a peticiones de usuarios (API)
  if not public.pambol_is_api_role() then return new; end if;

  if tg_op = 'INSERT' then
    new.points := 0; new.breakdown := null; new.scored_at := null;
  else
    new.points := old.points; new.breakdown := old.breakdown; new.scored_at := old.scored_at;
    if new.user_id <> old.user_id or new.gameweek_id <> old.gameweek_id then
      raise exception 'No se puede mover el equipo de jornada o de usuario';
    end if;
  end if;
  if new.user_id is distinct from auth.uid() then raise exception 'Solo puedes guardar tu propio equipo'; end if;
  if v_gw.status = 'scored' then raise exception 'La jornada ya fue cerrada y puntuada'; end if;
  if not exists (select 1 from public.fixtures where gameweek_id = new.gameweek_id and kickoff_at > now() and status = 'scheduled') then
    raise exception 'La jornada ya está cerrada: todos los partidos comenzaron';
  end if;

  -- Estructura del plantel
  if coalesce(array_length(new.starters, 1), 0) <> 11 then raise exception 'Debes alinear exactamente 11 titulares'; end if;
  if (select count(distinct x) from unnest(v_squad) x) <> 15 or array_length(v_squad, 1) <> 15 then
    raise exception 'La plantilla debe tener 15 futbolistas distintos (11 titulares + 4 suplentes)';
  end if;
  if (select count(*) from public.players where id = any(v_squad) and active) <> 15 then
    raise exception 'Hay futbolistas inválidos o dados de baja en tu plantilla';
  end if;
  if v_gk <> 1 or v_def not between 3 and 4 or v_mid not between 3 and 4 or v_fwd not between 3 and 4 then
    raise exception 'Formación inválida: usa 4-3-3, 3-4-3 o 3-3-4';
  end if;
  foreach v_bpos in array array['GK','DEF','MID','FWD'] loop
    if not exists (select 1 from public.players where id = (new.bench->>v_bpos)::int and pos = v_bpos) then
      raise exception 'La banca necesita 1 POR, 1 DEF, 1 MED y 1 DEL';
    end if;
  end loop;
  if not (new.captain_id = any(new.starters)) then raise exception 'El capitán debe ser titular'; end if;
  if not exists (select 1 from public.coaches where id = new.coach_id and active) then raise exception 'DT inválido'; end if;

  -- Modificadores: máximo 2, uno por jugador, solo de tu plantilla
  if jsonb_typeof(new.modifiers) <> 'object' then raise exception 'Modificadores inválidos'; end if;
  if (select count(*) from jsonb_object_keys(new.modifiers)) > 2 then raise exception 'Máximo 2 modificadores por jornada'; end if;
  for v_key, v_val in select key, value #>> '{}' from jsonb_each(new.modifiers) loop
    if v_key !~ '^\d+$' or not (v_key::int = any(v_squad)) then raise exception 'Modificador en un jugador que no es de tu plantilla'; end if;
    if v_val not in ('HACHERO','CHULADA','PARO','LEYEX','REVULSIVO') then raise exception 'Modificador desconocido: %', v_val; end if;
  end loop;

  -- Límite por club: 3 titulares y 5 en total
  if exists (select 1 from public.players where id = any(new.starters) group by club_short having count(*) > 3) then
    raise exception 'Máximo 3 titulares del mismo club';
  end if;
  if exists (select 1 from public.players where id = any(v_squad) group by club_short having count(*) > 5) then
    raise exception 'Máximo 5 futbolistas del mismo club';
  end if;

  -- Comodines: una vez por torneo
  if new.chip <> 'NONE' and exists (
    select 1 from public.fantasy_teams t join public.gameweeks g on g.id = t.gameweek_id
    where t.user_id = new.user_id and t.chip = new.chip and t.gameweek_id <> new.gameweek_id
      and g.tournament_id = v_gw.tournament_id) then
    raise exception 'Ese comodín ya lo usaste en este torneo';
  end if;

  -- Referencia para presupuesto y veda: versión guardada o equipo de la jornada anterior
  if tg_op = 'UPDATE' then
    b_starters := old.starters; b_bench := old.bench; b_captain := old.captain_id;
    b_mods := old.modifiers; b_coach := old.coach_id; b_chip := old.chip;
  elsif v_prev.id is not null then
    b_starters := v_prev.starters; b_bench := v_prev.bench; b_captain := v_prev.captain_id;
    b_mods := '{}'::jsonb; b_coach := v_prev.coach_id; b_chip := 'NONE';  -- los modificadores no se arrastran
  else
    b_starters := '{}'; b_bench := '{}'::jsonb; b_captain := null; b_mods := '{}'::jsonb; b_coach := null; b_chip := 'NONE';
  end if;
  v_old_squad := public.pambol_squad_ids(b_starters, b_bench);

  -- Presupuesto: 100.0 V (si cambiaste la plantilla o el DT)
  if new.squad_cost > 100.0 and (
       (select array_agg(x order by x) from unnest(v_squad) x) is distinct from (select array_agg(x order by x) from unnest(v_old_squad) x)
       or new.coach_id is distinct from b_coach) then
    raise exception 'Te pasas del presupuesto: % V de 100.0 V', new.squad_cost;
  end if;

  -- Veda por silbatazo: los jugadores cuyo partido ya empezó no se pueden mover
  v_locked := public.gw_locked_clubs(new.gameweek_id);
  if array_length(v_locked, 1) > 0 then
    foreach pid in array (v_squad || v_old_squad) loop
      select club_short into v_club from public.players where id = pid;
      if v_club = any(v_locked) and
         public.pambol_role(pid, new.starters, new.bench, new.captain_id, new.modifiers)
           is distinct from public.pambol_role(pid, b_starters, b_bench, b_captain, b_mods) then
        raise exception 'Veda: % ya está jugando y no se puede mover', (select name from public.players where id = pid);
      end if;
    end loop;
    if new.coach_id is distinct from b_coach and (
         (select club_short from public.coaches where id = new.coach_id) = any(v_locked)
         or (b_coach is not null and (select club_short from public.coaches where id = b_coach) = any(v_locked))) then
      raise exception 'Veda: tu DT ya está dirigiendo y no se puede cambiar';
    end if;
    if new.chip is distinct from b_chip and public.gw_deadline(new.gameweek_id) <= now() then
      raise exception 'Los comodines se cierran con el primer partido de la jornada';
    end if;
  end if;

  return new;
end $$;


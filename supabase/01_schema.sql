-- Crea el perfil automáticamente al registrarse
create or replace function public.pambol_ensure_profile(p_id uuid, p_email text, p_meta jsonb)
returns void language plpgsql security definer set search_path = public as $$
declare
  v_base text;
  v_name text;
  v_club text;
  v_n int := 0;
begin
  if exists (select 1 from public.profiles where id = p_id) then return; end if;
  v_base := regexp_replace(coalesce(p_meta->>'username', split_part(p_email, '@', 1), 'DT'),
                           '[^A-Za-z0-9_.ÁÉÍÓÚÜÑáéíóúüñ-]', '_', 'g');
  v_base := left(v_base, 20);
  if char_length(v_base) < 3 then v_base := v_base || '_DT'; end if;
  v_name := v_base;
  while exists (select 1 from public.profiles where lower(username) = lower(v_name)) loop
    v_n := v_n + 1;
    v_name := left(v_base, 19) || '_' || v_n::text;
  end loop;
  v_club := p_meta->>'favorite_club';
  if v_club is not null and not exists (select 1 from public.clubs where short = v_club) then
    v_club := null;
  end if;
  insert into public.profiles (id, username, full_name, favorite_club)
  values (p_id, v_name, left(coalesce(p_meta->>'full_name', p_meta->>'name'), 80), v_club)
  on conflict (id) do nothing;
end $$;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  perform public.pambol_ensure_profile(new.id, new.email, coalesce(new.raw_user_meta_data, '{}'::jsonb));
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();


-- Puntos de una plantilla en una jornada (núcleo del motor)
create or replace function public.pambol_score_squad(
  p_gw integer, p_starters integer[], p_bench jsonb, p_captain integer,
  p_mods jsonb, p_chip text, p_coach integer, p_penalty integer default 0
) returns jsonb language plpgsql stable as $$
declare
  pid integer;
  v_pos text;
  v_club text;
  r jsonb;
  st public.player_stats;
  v_players jsonb := '{}'::jsonb;
  v_pts numeric;
  v_lines jsonb;
  v_min int;
  v_done boolean;
  total numeric := 0;
  v_cap_mult int := case when p_chip = 'TRIPLE_CAP' then 3 else 2 end;
  v_squad integer[] := public.pambol_squad_ids(p_starters, p_bench);
  v_counted integer[] := '{}';
  v_bench_used text[] := '{}';
  bpos text;
  bpid integer;
  c_club text;
  c_pts numeric := 0;
  c_lines jsonb := '[]'::jsonb;
  fx record;
begin
  -- 1) Puntos crudos de cada jugador de la plantilla
  foreach pid in array v_squad loop
    select pos, club_short into v_pos, v_club from public.players where id = pid;
    v_pts := 0; v_lines := '[]'::jsonb; v_min := 0;
    for st in
      select s.* from public.player_stats s join public.fixtures f on f.id = s.fixture_id
      where f.gameweek_id = p_gw and s.player_id = pid
    loop
      r := public.pambol_stat_points(st, v_pos, coalesce(p_mods->>(pid::text), 'NONE'));
      v_pts := v_pts + (r->>'points')::numeric;
      v_lines := v_lines || (r->'lines');
      v_min := v_min + st.minutes;
    end loop;
    -- ¿Ya terminaron todos los partidos de su club en la jornada?
    select coalesce(bool_and(f.status in ('finished','postponed')), true) into v_done
      from public.fixtures f where f.gameweek_id = p_gw and (f.home_club = v_club or f.away_club = v_club);
    v_players := v_players || jsonb_build_object(pid::text, jsonb_build_object(
      'pos', v_pos, 'raw', v_pts, 'minutes', v_min, 'done', v_done, 'lines', v_lines,
      'starter', pid = any(p_starters), 'counted', false, 'captain', pid = p_captain,
      'sub_in', false, 'sub_out', false, 'points', 0));
  end loop;

  -- 2) Quién cuenta: titulares + cambios automáticos (mismo puesto) o Banca Blindada
  if p_chip = 'BENCH_BOOST' then
    v_counted := v_squad;
  else
    v_counted := p_starters;
    foreach pid in array p_starters loop
      if (v_players->pid::text->>'minutes')::int = 0 and (v_players->pid::text->>'done')::boolean then
        bpos := v_players->pid::text->>'pos';
        bpid := (p_bench->>bpos)::int;
        if bpid is not null and not (bpos = any(v_bench_used))
           and (v_players->bpid::text->>'minutes')::int > 0 then
          v_counted := array_remove(v_counted, pid) || bpid;
          v_bench_used := v_bench_used || bpos;
          v_players := jsonb_set(v_players, array[pid::text, 'sub_out'], 'true');
          v_players := jsonb_set(v_players, array[bpid::text, 'sub_in'], 'true');
        end if;
      end if;
    end loop;
  end if;

  -- 3) Capitán y total
  foreach pid in array v_counted loop
    v_pts := (v_players->pid::text->>'raw')::numeric;
    if pid = p_captain then v_pts := v_pts * v_cap_mult; end if;
    v_players := jsonb_set(v_players, array[pid::text, 'counted'], 'true');
    v_players := jsonb_set(v_players, array[pid::text, 'points'], to_jsonb(v_pts));
    total := total + v_pts;
  end loop;

  -- 4) Director técnico: Victoria +6 · Empate +2 · Derrota 0
  select club_short into c_club from public.coaches where id = p_coach;
  for fx in
    select * from public.fixtures f where f.gameweek_id = p_gw and (f.home_club = c_club or f.away_club = c_club)
      and f.status in ('live','finished') and f.home_score is not null and f.away_score is not null
  loop
    if (fx.home_club = c_club and fx.home_score > fx.away_score) or (fx.away_club = c_club and fx.away_score > fx.home_score) then
      c_pts := c_pts + 6; c_lines := c_lines || jsonb_build_array(jsonb_build_array('🏆 Victoria ' || fx.home_club || ' ' || fx.home_score || '-' || fx.away_score || ' ' || fx.away_club, 6));
    elsif fx.home_score = fx.away_score then
      c_pts := c_pts + 2; c_lines := c_lines || jsonb_build_array(jsonb_build_array('🤝 Empate ' || fx.home_club || ' ' || fx.home_score || '-' || fx.away_score || ' ' || fx.away_club, 2));
    else
      c_lines := c_lines || jsonb_build_array(jsonb_build_array('❌ Derrota ' || fx.home_club || ' ' || fx.home_score || '-' || fx.away_score || ' ' || fx.away_club, 0));
    end if;
  end loop;
  total := total + c_pts - coalesce(p_penalty, 0);

  return jsonb_build_object(
    'total', total, 'players', v_players,
    'coach', jsonb_build_object('id', p_coach, 'points', c_pts, 'lines', c_lines),
    'penalty', coalesce(p_penalty, 0), 'chip', p_chip, 'captain', p_captain,
    'captain_mult', v_cap_mult, 'computed_at', now());
end $$;

create or replace function public.pambol_score_team(p_team_id integer)
